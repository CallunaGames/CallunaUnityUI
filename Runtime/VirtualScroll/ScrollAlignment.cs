namespace Calluna.UI
{
    public enum ScrollAlignment
    {
        /// <summary>Aligns the item's leading edge with the viewport's leading edge.</summary>
        Start = 0,
        /// <summary>Centres the item within the viewport.</summary>
        Center = 1,
        /// <summary>Aligns the item's trailing edge with the viewport's trailing edge.</summary>
        End = 2,
    }
}
